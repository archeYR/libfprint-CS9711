/* Device-prefix -> key picker. The first call argument is the 3-byte
 * device-ID prefix the driver extracts from the device's identity
 * response. */
const guint8 *
validity_pick_rsa_modulus_for_device_id (const guint8 device_prefix[3])
{
  /* Key B: prefix 06 03 01 only */
  if (device_prefix[0] == 0x06 && device_prefix[1] == 0x03 && device_prefix[2] == 0x01)
    return validity_rsa_modulus_b;
  /* Key A: all other 06 xx xx variants */
  return validity_rsa_modulus_a;
}
